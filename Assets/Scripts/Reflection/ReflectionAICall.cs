using UnityEngine;
using System;
using System.Collections.Generic;
using System.Threading.Tasks;

[Serializable]
public class ReflectionFeedbackData
{
    public string AIresponse;
    public string quoteId;
    public string quoteText;
    public string quotefrom;
    //What the ML algorithm read from the player's three answers (overall + per answer)
    public ReflectionEmotionResult emotion = new ReflectionEmotionResult();
}
public class ReflectionAICall : MonoBehaviour
{
    //Used when the model can't run, so the player gets safe (neutral, supportive) content
    public const string UnknownValence = "unknown";

    private MLAlgorithm emotionAlgorithm;
    private InferenceEngineEmotionScorer emotionScorer;
    private bool emotionLoadFailed;

    public Task<ReflectionFeedbackData> GenerateFeedbackAsync(
        List<CheckpointQuestionData> questions
    )
    {
        if (questions == null || questions.Count != 3)
        {
            throw new InvalidOperationException("AI response needs 3 questions.");
        }

        foreach (CheckpointQuestionData question in questions)
        {
            if (question == null || question.status != QuestionStatus.Answered || string.IsNullOrWhiteSpace(question.answerText))
            {
                throw new InvalidOperationException("All questions must be answered before feedback.");
            }
        }

        Debug.Log("AI has received three answers");

        //The ML algorithm scores each answer on its own; any negative answer makes the overall result negative
        ReflectionEmotionResult emotion = ClassifyAnswers(questions);
        Debug.Log($"Detected valence: {emotion.overallValence}");

        ReflectionFeedbackData feedback = new ReflectionFeedbackData
        {
            //The 4th question and quote are still placeholders until the prompt/quote collection exists (PBI 8);
            //they will be picked using feedback.emotion
            AIresponse = "[TEST FEEDBACK — NOT GENERATED BY AI]\n" +
                "Thank you for answering the three questions. " +
                "Which answer stands out to you, and why?",
            quoteId = "test_quote_01",
            quoteText = "You can take one small step without knowing the full path",
            quotefrom = "Original in-game quote",
            emotion = emotion
        };

        return Task.FromResult(feedback);
    }

    private ReflectionEmotionResult ClassifyAnswers(List<CheckpointQuestionData> questions)
    {
        try
        {
            if (emotionAlgorithm == null && !emotionLoadFailed)
            {
                emotionAlgorithm = ReflectionMLLoader.Load(out emotionScorer);
            }
            if (emotionAlgorithm != null)
            {
                List<string> answers = questions.ConvertAll(question => question.answerText);
                return emotionAlgorithm.ClassifyAnswers(answers);
            }
        }
        catch (Exception ex)
        {
            emotionLoadFailed = emotionAlgorithm == null;
            Debug.LogException(ex);
        }

        //Fail-safe: if the model can't run, don't guess; mark it unknown so safe content is used
        return new ReflectionEmotionResult { overallValence = UnknownValence };
    }

    private void OnDestroy()
    {
        emotionScorer?.Dispose();
    }
}
