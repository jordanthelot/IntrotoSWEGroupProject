using UnityEngine;
using System;
using System.Collections.Generic;
using System.Threading.Tasks;

[Serializable]
public class ReflectionFeedbackData
{
    public string AIresponse;
    public string quoteId;
    public string quoteText;
    public string quotefrom;
}
public class ReflectionAICall : MonoBehaviour
{
    public Task<ReflectionFeedbackData> GenerateFeedbackAsync(
        List<CheckpointQuestionData> questions
    )
    {
        if (questions == null || questions.Count != 3)
        {
            throw new InvalidOperationException("AI response needs 3 questions.");
        }
        foreach (CheckpointQuestionData question in questions)
        {
            if (question == null || question.status != QuestionStatus.Answered || string.IsNullOrWhiteSpace(question.answerText))
            {
                throw new InvalidOperationException("All questions must be answered before feedback.");
            }
        }
        Debug.Log("AI has received three answers");

        ReflectionFeedbackData feedback = new ReflectionFeedbackData
        {
            AIresponse = "[TEST FEEDBACK — NOT GENERATED BY AI]\n" +
                "Thank you for answering the three questions. " +
                "Which answer stands out to you, and why?",
            quoteId = "test_quote_01",
            quoteText = "You can take one small step without knowing the full path",
            quotefrom = "Original in-game quote"
        };

        return Task.FromResult(feedback);
    }
    

}
